import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { assertExactD1Baseline, createD1CostBaseline } from "../benchmark/baseline.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const CONFIG_PATH = path.join(ROOT, "benchmark", "wrangler.local.jsonc");
const ZERO_DATABASE_ID = "00000000-0000-0000-0000-000000000000";
const RESULT_MARKER = "USER_FACING_BENCHMARK_RESULT=";
const SCALES = [100, 1_000, 10_000, 100_000];
const BASELINE_PATH = path.join(ROOT, "benchmark", "d1-cost-baseline.json");
const MAXIMUM_BUDGET_PATH = path.join(ROOT, "benchmark", "d1-maximum-budget.json");
const updateBaseline = process.argv.includes("--update-baseline");

function fail(message) {
  throw new Error(`Local benchmark guard: ${message}`);
}

function containsRemoteBinding(value) {
  if (Array.isArray(value)) return value.some(containsRemoteBinding);
  if (value === null || typeof value !== "object") return false;
  return Object.entries(value).some(
    ([key, nested]) => (key === "remote" && nested !== false) || containsRemoteBinding(nested),
  );
}

function validateLocalConfiguration() {
  if (process.argv.slice(2).some((argument) => argument.toLowerCase().includes("remote"))) {
    fail("remote command-line options are forbidden");
  }
  if (CONFIG_PATH.includes("wrangler.mvp.local")) fail("the pilot Wrangler file is forbidden");
  const configuration = JSON.parse(readFileSync(CONFIG_PATH, "utf8"));
  if (containsRemoteBinding(configuration)) fail("remote bindings are forbidden");
  const databases = configuration.d1_databases;
  if (!Array.isArray(databases) || databases.length !== 1) {
    fail("exactly one local D1 binding is required");
  }
  if (databases[0]?.database_id !== ZERO_DATABASE_ID) {
    fail("the D1 binding must use the all-zero local database ID");
  }
  if (databases[0]?.database_name !== "coffee-bot-benchmark-local") {
    fail("the pilot D1 database name is forbidden");
  }
}

function sourceDigest() {
  const relativePaths = [
    "benchmark/baseline.ts",
    "benchmark/contract.ts",
    "benchmark/statistics.ts",
    "benchmark/support.ts",
    "benchmark/user-facing.benchmark.ts",
    "benchmark/d1-maximum-budget.json",
    "benchmark/wrangler.local.jsonc",
    "scripts/run-d1-benchmark.mjs",
    "vitest.benchmark.config.ts",
    ...readdirSync(path.join(ROOT, "migrations"))
      .filter((name) => name.endsWith(".sql"))
      .sort((left, right) => left.localeCompare(right, "en"))
      .map((name) => `migrations/${name}`),
  ];
  const hash = createHash("sha256");
  for (const relativePath of relativePaths) {
    hash.update(relativePath);
    hash.update("\0");
    hash.update(readFileSync(path.join(ROOT, relativePath)));
    hash.update("\0");
  }
  return hash.digest("hex");
}

function assertMaximumBudget(report) {
  const budget = JSON.parse(readFileSync(MAXIMUM_BUDGET_PATH, "utf8"));
  for (const result of report.results) {
    for (const counter of ["bindingCalls", "statements", "rowsRead", "rowsWritten"]) {
      if (result.aggregate[counter].max > budget.operation[counter]) {
        fail(
          `${result.id} ${counter} ${String(result.aggregate[counter].max)} exceeds reviewed maximum ${String(budget.operation[counter])}`,
        );
      }
    }
  }
  for (const seed of report.seeds) {
    if (seed.databaseBytes > budget.databaseBytes[String(seed.scale)]) {
      fail(`${String(seed.scale)} database bytes exceed the reviewed maximum`);
    }
  }
}

function markdown(report) {
  const lines = [
    "# Fully Local User-Facing D1 Benchmark",
    "",
    "## Contract",
    "",
    "This report was generated by the complete Worker request path with a fully local Miniflare/workerd D1 database. Discord and Twitch APIs were deterministic in-memory mocks. The benchmark did not use Cloudflare credentials, the pilot Wrangler configuration, or a remote D1 database.",
    "",
    `- Input digest: \`${report.sourceDigest}\``,
    `- Generated: ${report.generatedAt}`,
    `- Scales: ${report.scales.map((scale) => scale.toLocaleString("en-US")).join(", ")} active requests`,
    `- Sampling: ${report.warmups} warmups and ${report.samplesPerOperation} measured samples`,
    `- Runtime: ${report.environment.runtime}`,
    `- Host: ${report.environment.platform} ${report.environment.release}, ${report.environment.cpu}`,
    `- Node.js: ${report.environment.node}`,
    "",
    "Wall times are local observations, not production latency limits. D1 rows read and rows written are the primary cost evidence. Statement counts and wall times are supporting regression signals.",
    "",
    "## Results",
    "",
    "| Active requests | Operation | Wall median ms | Wall p95 ms | D1 median ms | Binding calls | Statements | Rows read | Rows written |",
    "|---:|---|---:|---:|---:|---:|---:|---:|---:|",
  ];
  for (const result of report.results) {
    lines.push(
      `| ${result.scale.toLocaleString("en-US")} | ${result.label} | ${result.aggregate.wallMs.median} | ${result.aggregate.wallMs.p95} | ${result.aggregate.d1DurationMs.median} | ${result.aggregate.bindingCalls.median} | ${result.aggregate.statements.median} | ${result.aggregate.rowsRead.median.toLocaleString("en-US")} | ${result.aggregate.rowsWritten.median.toLocaleString("en-US")} |`,
    );
  }
  lines.push(
    "",
    "## Focused Normalized Costs",
    "",
    "| Active requests | Operation | Processed items | Rows read per item | Rows written per item |",
    "|---:|---|---:|---:|---:|",
  );
  for (const result of report.results) {
    const processedItems =
      result.id === "twitch.request.invalid.expired-receipts" ? 100 : undefined;
    if (processedItems === undefined) continue;
    lines.push(
      `| ${result.scale.toLocaleString("en-US")} | ${result.label} | ${processedItems} | ${(result.aggregate.rowsRead.median / processedItems).toFixed(2)} | ${(result.aggregate.rowsWritten.median / processedItems).toFixed(2)} |`,
    );
  }
  lines.push(
    "",
    "## Focused D1 Statement Groups",
    "",
    "| Active requests | Operation | Statement group | Statements | Rows read | Rows written |",
    "|---:|---|---|---:|---:|---:|",
  );
  for (const result of report.results) {
    for (const [group, counters] of Object.entries(result.statementGroups ?? {})) {
      lines.push(
        `| ${result.scale.toLocaleString("en-US")} | ${result.label} | ${group} | ${counters.statements} | ${counters.rowsRead.toLocaleString("en-US")} | ${counters.rowsWritten.toLocaleString("en-US")} |`,
      );
    }
  }
  lines.push(
    "",
    "## Seed Shape",
    "",
    "Each scale contains a deterministic skewed mix of PvP Seasonal, PvP, and PvE requests. It also contains the stated number of user mappings, corresponding mode-safe raid memberships, capacity-aware raids distributed across the supported map catalog, the same number of recent delivery receipts, and one canonical community record. Scenario fixtures are restored outside the measured window.",
    "",
    "| Active requests | Local D1 bytes |",
    "|---:|---:|",
  );
  for (const seed of report.seeds) {
    lines.push(
      `| ${seed.scale.toLocaleString("en-US")} | ${seed.databaseBytes.toLocaleString("en-US")} |`,
    );
  }
  lines.push(
    "",
    "Focused adversarial scenarios add 600 expired receipts and 1,000, 10,000, and 100,000 removed membership rows outside the measured window. They exercise complete Worker command paths without changing the stable active-request seed matrix. Legacy unassigned-request recovery is covered by deterministic integration tests because it is an authenticated deployment operation, not a user-facing command.",
    "",
    "## Cost Invariants",
    "",
    "- Identical samples must have identical D1 binding-call, statement, row-read, and row-write counts.",
    "- The hand-reviewed maximum budget is separate from the rewritable exact baseline.",
    "- One user operation must use no more than 50 D1 statements.",
    "- Statement and write counts must remain constant across scales.",
    "- Row reads must remain within the configured approximately-linear growth allowance.",
    "- Discord Queue must read fewer than 200 D1 rows at every scale and percentile.",
    "- Twitch Queue must read fewer than 220 D1 rows at every scale and percentile.",
    "- Discord Stats must use a constant statement count and write zero rows.",
    "- Rollup-maintaining request and raid-result mutations must keep constant writes and no more than 32 rows of cross-scale read growth.",
    "- Discord Users page reads must be scale-independent and write zero rows.",
    "- Discord Users missing-detail completion must use bounded reads and writes.",
    "- Queue and board Refresh operations must perform no request-assignment writes.",
    "- One due expired-receipt operation must remove exactly 100 expired receipts.",
    "- Removed membership history must not increase open-board D1 rows read with history size.",
    "",
  );
  return lines.join("\n");
}

validateLocalConfiguration();
const vitestPath = path.join(ROOT, "node_modules", "vitest", "vitest.mjs");
const scaleReports = [];
for (const scale of SCALES) {
  console.log(
    `Running fully local benchmark with ${scale.toLocaleString("en-US")} active requests...`,
  );
  const execution = spawnSync(
    process.execPath,
    [vitestPath, "run", "--config", "vitest.benchmark.config.ts", "--reporter=verbose"],
    {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      env: { ...process.env, BENCHMARK_SCALE: String(scale) },
    },
  );
  if (execution.status !== 0) {
    process.stdout.write(execution.stdout ?? "");
    process.stderr.write(execution.stderr ?? "");
    console.error(
      `Local Vitest benchmark failed (status ${String(execution.status)}, signal ${String(execution.signal)}, error ${execution.error?.message ?? "none"}).`,
    );
    process.exit(execution.status ?? 1);
  }
  const markerIndex = execution.stdout.lastIndexOf(RESULT_MARKER);
  if (markerIndex < 0) fail(`the ${scale} benchmark did not emit a result payload`);
  const markerLine = execution.stdout
    .slice(markerIndex + RESULT_MARKER.length)
    .split(/\r?\n/, 1)[0];
  if (markerLine === undefined || markerLine.length === 0) fail("the result payload was empty");
  scaleReports.push(JSON.parse(markerLine));
}
const combined = {
  ...scaleReports[0],
  scales: SCALES,
  seeds: scaleReports.flatMap((scaleReport) => scaleReport.seeds),
  results: scaleReports.flatMap((scaleReport) => scaleReport.results),
};
for (const operationId of new Set(combined.results.map((result) => result.id))) {
  const operationResults = combined.results.filter((result) => result.id === operationId);
  const statements = new Set(operationResults.map((result) => result.aggregate.statements.median));
  const bindingCalls = new Set(
    operationResults.map((result) => result.aggregate.bindingCalls.median),
  );
  const writes = new Set(operationResults.map((result) => result.aggregate.rowsWritten.median));
  if (statements.size !== 1) fail(`${operationId} statement count changed with scale`);
  if (bindingCalls.size !== 1) fail(`${operationId} binding-call count changed with scale`);
  if (writes.size !== 1) fail(`${operationId} row writes changed with scale`);
  let queueRowLimit;
  if (operationId.startsWith("discord.queue.")) {
    queueRowLimit = 200;
  } else if (operationId.startsWith("twitch.queue.")) {
    queueRowLimit = 220;
  }
  if (
    queueRowLimit !== undefined &&
    operationResults.some((result) => result.aggregate.rowsRead.max >= queueRowLimit)
  ) {
    fail(`${operationId} must read fewer than ${queueRowLimit} rows`);
  }
  if (
    operationId === "discord.stats.all-time" &&
    operationResults.some((result) => result.aggregate.rowsWritten.max !== 0)
  ) {
    fail(`${operationId} must not write D1 rows`);
  }
  if (operationId === "discord.stats.all-time") {
    const statsReads = new Set(operationResults.map((result) => result.aggregate.rowsRead.median));
    if (statsReads.size !== 1) fail(`${operationId} row reads changed with scale`);
  }
  if (
    operationId === "discord.request.submit.created" ||
    operationId === "discord.raid.result.helped"
  ) {
    const mutationReads = operationResults.map((result) => result.aggregate.rowsRead.median);
    if (Math.max(...mutationReads) - Math.min(...mutationReads) > 32) {
      fail(
        `${operationId} row reads ${mutationReads.join(", ")} grew by more than the bounded index-depth allowance; groups ${JSON.stringify(
          operationResults.map((result) => ({
            scale: result.scale,
            statementGroups: result.statementGroups,
          })),
        )}`,
      );
    }
  }
  if (
    operationId.startsWith("discord.users.") &&
    operationId !== "discord.users.complete-discord"
  ) {
    if (operationResults.some((result) => result.aggregate.rowsWritten.max !== 0)) {
      fail(`${operationId} must not write D1 rows`);
    }
    const pageReads = new Set(operationResults.map((result) => result.aggregate.rowsRead.median));
    if (pageReads.size !== 1) fail(`${operationId} row reads changed with scale`);
  }
  if (
    operationId === "discord.users.complete-discord" &&
    operationResults.some(
      (result) => result.aggregate.rowsRead.max > 20 || result.aggregate.rowsWritten.max > 8,
    )
  ) {
    fail(`${operationId} must keep D1 reads and writes bounded`);
  }
  if (operationId === "discord.board.refresh.removed-history") {
    const historyReadOverhead = new Set(
      operationResults.map((result) => {
        const regular = combined.results.find(
          (candidate) =>
            candidate.id === "discord.board.refresh" && candidate.scale === result.scale,
        );
        if (regular === undefined) fail("the regular board Refresh benchmark is missing");
        return result.aggregate.rowsRead.median - regular.aggregate.rowsRead.median;
      }),
    );
    if (historyReadOverhead.size !== 1 || Math.max(...historyReadOverhead) > 20) {
      fail(`${operationId} added row reads changed with history size`);
    }
  }
  if (operationId === "discord.board.refresh") {
    if (
      operationResults.some(
        (result) => result.aggregate.statements.max > 6 || result.aggregate.rowsRead.max > 250,
      )
    ) {
      fail(`${operationId} exceeded its six-statement or 250-row-read limit`);
    }
  }
  if (
    (operationId.includes(".queue.") || operationId === "discord.board.refresh") &&
    operationResults.some((result) =>
      Object.keys(result.statementGroups ?? {}).some((group) => group.startsWith("assignment.")),
    )
  ) {
    fail(`${operationId} performed request-assignment work`);
  }
  if (operationId === "twitch.request.invalid") {
    if (
      operationResults.some(
        (result) =>
          result.aggregate.statements.max > 5 ||
          result.aggregate.rowsRead.max > 20 ||
          result.aggregate.rowsWritten.max !== 3,
      )
    ) {
      fail(`${operationId} exceeded its invalid-input D1 limit`);
    }
  }
  if (operationId === "twitch.request.invalid.expired-receipts") {
    if (
      operationResults.some(
        (result) =>
          result.aggregate.statements.max > 5 ||
          result.aggregate.rowsRead.max > 450 ||
          result.aggregate.rowsWritten.max > 104,
      )
    ) {
      fail(`${operationId} exceeded its leased-cleanup D1 limit`);
    }
  }
  for (let index = 1; index < operationResults.length; index += 1) {
    const previous = operationResults[index - 1];
    const current = operationResults[index];
    if (current.aggregate.rowsRead.median > previous.aggregate.rowsRead.median * 12 + 100) {
      fail(`${operationId} rows read grew faster than the allowed linear shape`);
    }
  }
}
const report = {
  ...combined,
  generatedAt: new Date().toISOString(),
  sourceDigest: sourceDigest(),
  environment: {
    runtime: "local Miniflare/workerd D1",
    node: process.version,
    platform: os.platform(),
    release: os.release(),
    cpu: os.cpus()[0]?.model ?? "unknown",
  },
};
assertMaximumBudget(report);
const jsonReportPath = path.join(ROOT, "reports", "d1-user-facing-benchmark.json");
writeFileSync(jsonReportPath, `${JSON.stringify(report, null, 2)}\n`);
writeFileSync(path.join(ROOT, "reports", "d1-user-facing-benchmark.md"), markdown(report));
if (updateBaseline) {
  writeFileSync(BASELINE_PATH, `${JSON.stringify(createD1CostBaseline(report), null, 2)}\n`);
}
const biomePath = path.join(ROOT, "node_modules", "@biomejs", "biome", "bin", "biome");
const formattedPaths = updateBaseline ? [jsonReportPath, BASELINE_PATH] : [jsonReportPath];
const formatting = spawnSync(
  process.execPath,
  [biomePath, "format", "--write", ...formattedPaths],
  { cwd: ROOT, encoding: "utf8" },
);
if (formatting.status !== 0) {
  process.stdout.write(formatting.stdout ?? "");
  process.stderr.write(formatting.stderr ?? "");
  fail("Biome could not format the JSON report");
}
if (updateBaseline) {
  console.log("Updated benchmark/d1-cost-baseline.json from fully local D1.");
} else {
  const baseline = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));
  assertExactD1Baseline(report, baseline);
  console.log("Exact D1 statement, row-read, and row-write counters match the baseline.");
}
console.log("Generated reports/d1-user-facing-benchmark.json and .md from fully local D1.");
